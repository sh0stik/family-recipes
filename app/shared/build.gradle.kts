// --- Build-time backend config (prod-ready) -------------------------------------------------
// The GraphQL host and scheme are baked into a generated `data.AppConfig` at build time, so no
// local IP or http:// is hardcoded in source. Build type is resolved, in order:
//   1. -Precipe.buildType, explicit and always wins (this is how Android CI/CLI drives it)
//   2. the $CONFIGURATION env var Xcode sets on every script phase, including the CocoaPods
//      `syncFramework` invocation that builds the framework for an Xcode Release archive — this
//      is what makes a TestFlight/Release build pick "release" with zero iOS-side wiring
//   3. inferred from the Gradle task graph (anything containing "Release")
//   4. "debug"
// (2) exists because `syncFramework`'s own task name never contains "Release", so (3) can't see
// it — an Xcode Release build without (2) would silently fall through to (4) and ship the local
// debug host. Do not "fix" this again by hand-editing the generated, gitignored
// shared/shared.podspec; it is regenerated from the `cocoapods { }` block below on every
// `pod install` and any edit there is lost.
//   Debug   -> http  + recipe.serverHost.debug (local backend by default)
//   Release -> https + recipe.serverHost.release (MUST be supplied; build fails otherwise)
// Supply the release host with -Precipe.serverHost.release=<host[:port]> or env
// RECIPE_SERVER_HOST_RELEASE. Example release build:
//   ./gradlew :androidApp:assembleRelease -Precipe.serverHost.release=api.example.com
val recipeBuildType: String = run {
    val explicit = (findProperty("recipe.buildType") as String?)?.takeIf { it.isNotBlank() }
    val xcodeConfiguration = System.getenv("CONFIGURATION")?.takeIf { it.isNotBlank() }
    val looksLikeRelease = gradle.startParameter.taskNames.any { it.contains("Release") }
    explicit
        ?: xcodeConfiguration?.let { if (it.equals("Release", ignoreCase = true)) "release" else "debug" }
        ?: if (looksLikeRelease) "release" else "debug"
}
val recipeServerHost: String = if (recipeBuildType == "release") {
    ((findProperty("recipe.serverHost.release") as String?)?.takeIf { it.isNotBlank() }
        ?: System.getenv("RECIPE_SERVER_HOST_RELEASE")?.takeIf { it.isNotBlank() })
        ?: throw GradleException(
            "Release build requires a backend host. Pass -Precipe.serverHost.release=<host[:port]> " +
                "or set the RECIPE_SERVER_HOST_RELEASE environment variable."
        )
} else {
    (findProperty("recipe.serverHost.debug") as String?)?.takeIf { it.isNotBlank() } ?: "localhost:8080"
}
val recipeUseHttps: Boolean = recipeBuildType == "release"

val generateAppConfig by tasks.registering {
    val outDir = layout.buildDirectory.dir("generated/appConfig/commonMain/kotlin")
    inputs.property("serverHost", recipeServerHost)
    inputs.property("useHttps", recipeUseHttps)
    inputs.property("buildType", recipeBuildType)
    outputs.dir(outDir)
    doLast {
        val pkgDir = outDir.get().asFile.resolve("data").apply { mkdirs() }
        pkgDir.resolve("AppConfig.kt").writeText(
            """
            // GENERATED by the :shared generateAppConfig task — do not edit.
            // buildType=$recipeBuildType
            package data

            object AppConfig {
                const val SERVER_HOST: String = "$recipeServerHost"
                const val USE_HTTPS: Boolean = $recipeUseHttps
                val SCHEME: String get() = if (USE_HTTPS) "https" else "http"
                val BASE_URL: String get() = "${'$'}SCHEME://${'$'}SERVER_HOST"
            }
            """.trimIndent() + "\n"
        )
    }
}

