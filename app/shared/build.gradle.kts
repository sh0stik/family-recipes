                // Ktor 2.2.2's ktor-client-core API (HttpTimeout plugin install, etc).
                // Android (OkHttp) and iOS (Darwin) never route Apollo through Ktor at all,
                // so they can take coil's Ktor-3 network artifact freely below. If Ktor 3.x
                // and 2.x both land on the js() classpath, Gradle's "highest version wins"
                // conflict resolution bumps ktor-client-core to 3.x under Apollo's JS engine,
                // which still expects the 2.x API shape (e.g. HttpTimeout.Plugin) -- Kotlin/JS
                // resolves that mismatch lazily at runtime as an unresolved-symbol stub:
                //   "Can not get instance of singleton 'Plugin': No class found for symbol
                //    'io.ktor.client.plugins/HttpTimeout.Plugin|null[0]'"
                // See the jsMain source set below for the Ktor-2-compatible replacement.
            }
        }

