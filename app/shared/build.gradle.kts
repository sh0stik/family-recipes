                api(libs.androidx.core.ktx)
                implementation("io.coil-kt.coil3:coil-network-ktor3:3.1.0")
                // Coil's Ktor fetcher brings no Ktor engine. Without one every photo failed with
                // "Failed to find HTTP client engine implementation" before any request was sent
